#!/usr/bin/env python3
"""Generate the tossctl agent skill's operation catalog and sync its embedded copy.

The skill (`skills/tossctl/SKILL.md`) is hand-authored and stable. The part that
must track development — the list of operations — is generated here from the
single source of truth, the `internal/ops` registry, surfaced via
`tossctl ops list`. Regenerating on every registry change (and enforcing it in
CI with `--check`) is what keeps "update the skill alongside development" from
being a promise nobody keeps: add or rename an operation and the skill drifts
until this runs, and CI fails the PR that forgot to.

The binary ships the same skill embedded (so `tossctl skill install` works
offline), under `internal/skill/assets/`. That copy is a *mirror* of the
canonical `skills/tossctl/` source, not a second source: this script writes the
generated catalog to both the distributable path and the embed mirror, and
copies the hand-authored SKILL.md into the mirror too. `--check` verifies every
managed path, so the embedded skill can never fall behind the one users curl.

Usage:
    python3 tools/build_skill.py           # regenerate catalog + sync embed mirror
    python3 tools/build_skill.py --check    # fail if any managed path is out of sync (CI)

The tossctl binary is `go run ./cmd/tossctl` by default (builds from the repo
source so CI validates the PR's own registry); override with TOSSCTL_BIN or
--bin for a prebuilt binary. `ops list` reads the static catalog and needs no
session.
"""
from __future__ import annotations

import argparse
import json
import os
import shlex
import subprocess
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Canonical, distributable skill (curl|sh installs these; skills/README.md).
SRC_SKILL = os.path.join(REPO_ROOT, "skills", "tossctl", "SKILL.md")
OUT = os.path.join(REPO_ROOT, "skills", "tossctl", "references", "operations.md")

# Embedded mirror the binary ships (go:embed; `tossctl skill install`). Kept in
# lockstep with the canonical source above — see module docstring.
EMBED_SKILL = os.path.join(REPO_ROOT, "internal", "skill", "assets", "SKILL.md")
EMBED_OPS = os.path.join(
    REPO_ROOT, "internal", "skill", "assets", "references", "operations.md"
)

GENERATED_NOTE = (
    "<!-- GENERATED by tools/build_skill.py from the ops registry "
    "(tossctl ops list). Do not edit by hand; run the script. -->"
)


def load_operations(bin_cmd: str) -> list[dict]:
    # Pin an empty config directory so the catalog is the stable DEFAULT surface,
    # identical in CI and on any machine. A developer's local config (e.g.
    # experimental.paper_trading=true) otherwise adds opt-in operations that CI's
    # clean environment lacks, flapping the sync check. Opt-in and experimental
    # operations are intentionally excluded from the written catalog — an agent
    # discovers them live via list_operations once they are enabled. --config-dir
    # (not HOME) keeps go-run's module/build caches intact.
    import tempfile
    with tempfile.TemporaryDirectory() as cfg:
        argv = shlex.split(bin_cmd) + ["ops", "list", "--config-dir", cfg]
        proc = subprocess.run(
            argv, cwd=REPO_ROOT, capture_output=True, text=True, timeout=300
        )
    if proc.returncode != 0:
        sys.exit(f"`{' '.join(argv)}` failed (exit {proc.returncode}):\n{proc.stderr.strip()}")
    try:
        data = json.loads(proc.stdout)
    except json.JSONDecodeError as exc:
        sys.exit(f"ops list did not return JSON: {exc}")
    ops = data.get("operations", [])
    if not ops:
        sys.exit("ops list returned no operations")
    return ops


def render(ops: list[dict]) -> str:
    # Deterministic grouping so the file is stable across runs (CI diffs it).
    by_cat: dict[str, list[dict]] = {}
    for op in ops:
        by_cat.setdefault(op.get("category", "other"), []).append(op)

    lines = [
        GENERATED_NOTE,
        "",
        "# tossctl operations",
        "",
        f"{len(ops)} operations, grouped by category. Each is callable by `id` via "
        "`call_operation` (MCP) or `tossctl ops call <id>`. Always confirm the "
        "current parameter schema with `describe_operation` before calling — this "
        "list is a map, not the contract.",
        "",
        "Columns: **backend** = credential channel (`wts` web session · `official` "
        "Open API · `auto` either · `none` local); **write** = mutates state "
        "(preview-then-confirm, gated); **required** = params you must pass.",
        "",
    ]
    for cat in sorted(by_cat):
        lines.append(f"## {cat}")
        lines.append("")
        lines.append("| id | backend | write | required | summary |")
        lines.append("| --- | --- | --- | --- | --- |")
        for op in sorted(by_cat[cat], key=lambda o: o["id"]):
            backend = op.get("backend", "wts")
            write = "yes" if op.get("write") else ""
            required = ", ".join(op.get("required", []) or [])
            summary = (op.get("summary", "") or "").replace("|", "\\|").replace("\n", " ")
            lines.append(
                f"| `{op['id']}` | {backend} | {write} | {required} | {summary} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _read(path: str) -> str | None:
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def managed_files(catalog: str, skill_md: str) -> dict[str, str]:
    """Map every path this script owns to the exact contents it must have.

    `catalog` is the generated operations.md (identical in both homes). `skill_md`
    is the canonical SKILL.md, mirrored verbatim into the embed copy. SRC_SKILL
    itself is hand-authored and never written here — it is the source, not a
    managed output.
    """
    return {OUT: catalog, EMBED_OPS: catalog, EMBED_SKILL: skill_md}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if any managed file is out of sync")
    ap.add_argument("--bin", default=os.environ.get("TOSSCTL_BIN", "go run ./cmd/tossctl"),
                    help="tossctl invocation (default: 'go run ./cmd/tossctl')")
    args = ap.parse_args()

    skill_md = _read(SRC_SKILL)
    if skill_md is None:
        sys.exit(f"canonical skill missing: {os.path.relpath(SRC_SKILL, REPO_ROOT)}")

    files = managed_files(render(load_operations(args.bin)), skill_md)

    if args.check:
        drifted = [path for path, want in files.items() if _read(path) != want]
        if drifted:
            listing = "\n".join(f"  {os.path.relpath(p, REPO_ROOT)}" for p in sorted(drifted))
            sys.stderr.write(
                "the agent skill is out of sync with the ops registry / canonical "
                f"source:\n{listing}\nRun: python3 tools/build_skill.py\n"
            )
            return 1
        print("skill catalog + embedded copy are in sync")
        return 0

    for path, want in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(want)
    wrote = ", ".join(os.path.relpath(p, REPO_ROOT) for p in sorted(files))
    print(f"wrote {wrote}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
